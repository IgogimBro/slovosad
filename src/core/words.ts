export function validateWord(word: Word, others: Word[]): string | null {
  const spelling = normalize(word.spelling);
  if (!/^[А-ЯЁ]{2,16}$/u.test(spelling))
    return 'Введите одно русское слово: от 2 до 16 букв, без пробелов.';
  if (!word.category.trim()) return 'Укажите категорию.';
  if (others.some((w) => w.id !== word.id && w.spelling === spelling))
    return 'Такое слово уже есть в словаре.';
  const wrong = word.distractors.map((d) => normalize(d.text));
  if (
    wrong.some(
      (t) => !/^[А-ЯЁ]{2,18}$/u.test(t) || t === spelling || others.some((w) => w.spelling === t),
    )
  )
    return 'Неверные варианты должны быть русскими буквами и не совпадать с настоящими словами словаря.';
  if (new Set(wrong).size !== wrong.length) return 'Неверные варианты должны различаться.';
  if ((word.modes.includes('spelling') || word.modes.includes('correct')) && wrong.length < 3)
    return 'Для выбора написания и исправления добавьте три проверенных неверных варианта.';
  if (word.modes.includes('correct') && !wrong.some((text) => editDistance(spelling, text) === 1))
    return 'Для исправления нужен хотя бы один вариант с одной ошибкой.';
  if (!word.modes.length) return 'Выберите хотя бы один режим.';
  return null;
}
