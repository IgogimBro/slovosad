export function classifyError(target: string, answer: string): ErrorKind {
  if (answer.length < target.length) return 'missing';
  if (answer.length > target.length) return /([А-ЯЁ])\1/u.test(answer) ? 'repeated' : 'extra';
  const diffs = [...target].map((c, i) => (c !== answer[i] ? i : -1)).filter((i) => i >= 0);
  if (
    diffs.length === 2 &&
    diffs[1] === diffs[0] + 1 &&
    target[diffs[0]] === answer[diffs[1]] &&
    target[diffs[1]] === answer[diffs[0]]
  )
    return 'swapped';
  if (diffs.length === 1) {
    const pair = [target[diffs[0]], answer[diffs[0]]].sort().join('');
    if (pair === 'ИЙ') return 'и/й';
    if (pair === 'ИЫ') return 'ы/и';
    return /[АЕЁИОУЫЭЮЯ]/u.test(target[diffs[0]]) ? 'vowel' : 'consonant';
  }
  return 'other';
}
export function editDistance(a: string, b: string): number {
  let previous = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const row = [i];
    for (let j = 1; j <= b.length; j++)
      row[j] = Math.min(
        row[j - 1] + 1,
        previous[j] + 1,
        previous[j - 1] + Number(a[i - 1] !== b[j - 1]),
      );
    previous = row;
  }
  return previous[b.length];
}
